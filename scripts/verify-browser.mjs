import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const base = 'https://azerothsurvivors-release-staging.sandervispoel.workers.dev';
const checks = [];
const report = { base, startedAt: new Date().toISOString(), passed: false, checks };
const { password } = JSON.parse(await readFile(new URL('../.local/staging-credential.json', import.meta.url)));
const name = 'Azeroth Survivors - Windows build & download mirror - long filename é新.rar';
const path = fileURLToPath(new URL(`../.local/${name}`, import.meta.url));
const bytes = await readFile(path);
const expected = { sha256: createHash('sha256').update(bytes).digest('hex'), md5: createHash('md5').update(bytes).digest('hex') };
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const context = await browser.newContext({ viewport: { width: 1000, height: 900 } });
const page = await context.newPage();
page.setDefaultTimeout(30000);
let partOneRequests = 0;
page.on('request', request => { if (request.url().endsWith('/parts/1') && request.method() === 'PUT') partOneRequests++; });
try {
  await page.goto(base + '/admin');
  await page.locator('#login-view').getByLabel('Password', { exact: true }).fill('incorrect-password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Incorrect password.' })).toBeVisible();
  await page.locator('#login-view').getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Manage releases.' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Upload & publish', exact: true })).toBeEnabled();
  const previous = await fetch(base + '/api/release').then(r => r.json());
  const cookie = (await context.cookies()).find(value => value.name === '__Host-mirror_session');
  assert.ok(cookie.httpOnly && cookie.secure && cookie.sameSite === 'Strict');
  checks.push({ name: 'Wrong-password feedback, successful sign-in, and protected session cookie', passed: true });
  await page.route('**/parts/2', route => route.abort());
  await page.getByLabel('Archive', { exact: true }).setInputFiles(path);
  await page.getByLabel('Version label', { exact: false }).fill('Browser upload - resume verified');
  await page.getByRole('button', { name: 'Upload & publish', exact: true }).click();
  await expect(page.locator('#upload-message')).toContainText('Choose the same file and resume', { timeout: 180000 });
  assert.equal((await fetch(base + '/api/release').then(r => r.json())).id, previous.id);
  assert.equal(partOneRequests, 1);
  checks.push({ name: 'Network interruption after part one keeps the existing release live and offers resume', passed: true });
  await page.unroute('**/parts/2');
  await page.reload();
  await expect(page.getByRole('button', { name: 'Resume upload & publish', exact: true })).toBeEnabled();
  await page.getByLabel('Archive', { exact: true }).setInputFiles(path);
  await page.getByRole('button', { name: 'Resume upload & publish', exact: true }).click();
  await expect(page.locator('#upload-message')).toContainText('Published.', { timeout: 180000 });
  assert.equal(partOneRequests, 1);
  const release = await fetch(base + '/api/release').then(r => r.json());
  assert.notEqual(release.id, previous.id);
  assert.equal(release.sha256, expected.sha256); assert.equal(release.md5, expected.md5);
  const download = Buffer.from(await fetch(new URL(release.downloadUrl, base)).then(r => r.arrayBuffer()));
  assert.deepEqual(download, bytes);
  checks.push({ name: 'Reloaded page resumes without resending part one; browser SHA-256 and MD5 match independent Node hashes and full download', passed: true });
  report.published = { id: release.id, bytes: bytes.length, ...expected };
  await mkdir(new URL('../artifacts/', import.meta.url), { recursive: true });
  await page.screenshot({ path: fileURLToPath(new URL('../artifacts/admin-desktop.png', import.meta.url)), fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: fileURLToPath(new URL('../artifacts/admin-mobile.png', import.meta.url)), fullPage: true });
  checks.push({ name: 'Desktop and 375px mobile upload/history layout renders without horizontal overflow', passed: true });
  const previousRow = page.locator('.release').filter({ has: page.locator(`a[href*="/${previous.id}/"]`) });
  await previousRow.getByRole('button', { name: 'Make current', exact: true }).click();
  await expect(page.locator('#history-message')).toContainText('now serves the selected version');
  assert.equal((await fetch(base + '/api/release').then(r => r.json())).id, previous.id);
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sign in to manage the mirror.' })).toBeVisible();
  checks.push({ name: 'Release activation rolls back the mirror and sign-out returns to the login screen', passed: true });
  report.passed = true;
} catch (error) {
  report.error = error.stack; process.exitCode = 1; console.error(error);
  await page.screenshot({ path: fileURLToPath(new URL('../.local/browser-failure.png', import.meta.url)), fullPage: true }).catch(() => {});
} finally {
  report.finishedAt = new Date().toISOString();
  await mkdir(new URL('../artifacts/', import.meta.url), { recursive: true });
  await writeFile(new URL('../artifacts/browser-e2e.json', import.meta.url), JSON.stringify(report, null, 2) + '\n');
  await browser.close();
  console.log('Browser evidence written to artifacts/browser-e2e.json');
}
